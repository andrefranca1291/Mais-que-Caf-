-- Estrutura PostgreSQL para o sistema web Mais Que Café.
-- Execute uma única vez no banco PostgreSQL hospedado.

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    senha VARCHAR(255) NOT NULL,
    telefone VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS produto (
    id_produto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL,
    descricao TEXT,
    preco NUMERIC(10, 2) NOT NULL,
    categoria VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS pedido (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL REFERENCES cliente(id_cliente),
    data_pedido TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    valor_total NUMERIC(10, 2),
    status VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS item_pedido (
    id_item INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER NOT NULL REFERENCES pedido(id_pedido),
    id_produto INTEGER NOT NULL REFERENCES produto(id_produto),
    quantidade INTEGER NOT NULL,
    subtotal NUMERIC(10, 2)
);

CREATE TABLE IF NOT EXISTS pagamento (
    id_pagamento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER REFERENCES pedido(id_pedido),
    tipo_pagamento VARCHAR(100),
    valor NUMERIC(10, 2),
    status_pagamento VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS entrega (
    id_entrega INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido INTEGER REFERENCES pedido(id_pedido),
    endereco VARCHAR(255),
    data_agendada TIMESTAMP WITHOUT TIME ZONE,
    status_entrega VARCHAR(50)
);

CREATE INDEX IF NOT EXISTS ix_pedido_cliente ON pedido(id_cliente);
CREATE INDEX IF NOT EXISTS ix_item_pedido_pedido ON item_pedido(id_pedido);
CREATE INDEX IF NOT EXISTS ix_item_pedido_produto ON item_pedido(id_produto);
CREATE INDEX IF NOT EXISTS ix_pagamento_pedido ON pagamento(id_pedido);
CREATE INDEX IF NOT EXISTS ix_entrega_pedido ON entrega(id_pedido);
